//! Codex CLI install facts: version policy, install-method detection and
//! `codex update`.
use std::path::{Path, PathBuf};
use std::time::Duration;

use openbitfun_core::util::errors::{OpenBitFunError, OpenBitFunResult};

use crate::client::config::{AcpRequirementProbeItem, NativeCliInstallMethod, NativeCliStatus};
use crate::client::requirements::{command_error_summary, run_command_with_timeout};

/// Lowest Codex release the app-server driver is verified against. The driver
/// relies on `turn/steer`, `thread/fork { lastTurnId }`, `model/list` and the
/// v2 item notifications as generated by `codex app-server generate-ts` for
/// 0.163.0; earlier releases are not verified.
pub(crate) const MIN_VERSION: &str = "0.163.0";
pub(crate) const DOCS_URL: &str = "https://developers.openai.com/codex/cli";
const INSTALL_COMMAND: &str = "npm install -g @openai/codex";
const UPDATE_TIMEOUT: Duration = Duration::from_secs(300);

/// First `x.y.z` token, e.g. `codex-cli 0.163.0` or the initialize
/// `userAgent` (`codex_cli_rs/0.163.0 (Windows 10.0; x86_64) ...`).
pub(crate) fn parse_version(output: &str) -> Option<semver::Version> {
    output
        .split(|c: char| c.is_whitespace() || c == '/')
        .find_map(|token| {
            let token = token.trim_start_matches('v');
            let core = token
                .split(|c: char| !(c.is_ascii_digit() || c == '.'))
                .next()
                .unwrap_or_default();
            if core.split('.').count() != 3 {
                return None;
            }
            semver::Version::parse(core).ok()
        })
}

pub(crate) fn is_too_old(output: &str) -> Option<bool> {
    let version = parse_version(output)?;
    Some(version < semver::Version::parse(MIN_VERSION).ok()?)
}

pub(crate) fn detect_install_method(path: &str) -> NativeCliInstallMethod {
    let normalized = path.replace('\\', "/").to_ascii_lowercase();
    let has = |needle: &str| normalized.contains(needle);
    if has("/node_modules/")
        || has("/npm/")
        || has("/.npm-global/")
        || has("/nvm")
        || has("/fnm/")
        || has("/volta/")
        || has("/nodejs/")
        || normalized.ends_with("/codex.cmd")
        || normalized.ends_with("/codex.ps1")
    {
        NativeCliInstallMethod::Npm
    } else if has("/cellar/") || has("/caskroom/") || has("/homebrew/") || has("/linuxbrew/") {
        NativeCliInstallMethod::Homebrew
    } else if has("/winget/") {
        NativeCliInstallMethod::Winget
    } else {
        NativeCliInstallMethod::Unknown
    }
}

pub(crate) fn cli_status(
    tool: &AcpRequirementProbeItem,
    _windows: bool,
    remote: bool,
) -> NativeCliStatus {
    let version = tool.version.as_deref().and_then(parse_version);
    NativeCliStatus {
        install_method: tool
            .path
            .as_deref()
            .map(detect_install_method)
            .unwrap_or_default(),
        version: version.map(|version| version.to_string()),
        min_version: MIN_VERSION.to_string(),
        too_old: tool
            .version
            .as_deref()
            .and_then(is_too_old)
            .unwrap_or(false),
        update_supported: tool.installed && !remote,
        install_command: Some(INSTALL_COMMAND.to_string()),
        docs_url: Some(DOCS_URL.to_string()),
    }
}

pub(crate) fn too_old_message(found: &str) -> String {
    format!(
        "Codex {found} is older than the minimum supported version {MIN_VERSION}. \
         Run `codex update` (or update it from Settings > External agents), then retry."
    )
}

/// Gate a running app-server on [`MIN_VERSION`] using its initialize
/// `userAgent`; unparsable versions are logged and allowed.
pub(crate) fn check_user_agent(user_agent: Option<&str>) -> OpenBitFunResult<()> {
    let Some(agent) = user_agent else {
        log::warn!("Codex version check skipped: initialize has no userAgent");
        return Ok(());
    };
    match is_too_old(agent) {
        Some(true) => Err(OpenBitFunError::Validation(too_old_message(
            &parse_version(agent)
                .map(|version| version.to_string())
                .unwrap_or_else(|| agent.to_string()),
        ))),
        Some(false) => Ok(()),
        None => {
            log::warn!("Codex version check skipped: unparsable userAgent {agent}");
            Ok(())
        }
    }
}

/// `codex` on PATH; npm installs a `.cmd` shim on Windows, which a bare
/// command name would not resolve.
pub(crate) fn local_executable() -> PathBuf {
    crate::client::requirements::find_executable_with_path("codex", None)
        .unwrap_or_else(|| PathBuf::from("codex"))
}

pub(crate) async fn run_update(executable: &Path) -> OpenBitFunResult<String> {
    let output = run_command_with_timeout(executable.as_os_str(), ["update"], UPDATE_TIMEOUT)
        .await
        .map_err(|error| {
            OpenBitFunError::service(format!("Failed to run `codex update`: {error}"))
        })?;
    if !output.status.success() {
        return Err(OpenBitFunError::service(format!(
            "`codex update` failed: {}",
            command_error_summary(&output.stderr, &output.stdout)
        )));
    }
    let stdout = String::from_utf8_lossy(&output.stdout).trim().to_string();
    let stderr = String::from_utf8_lossy(&output.stderr).trim().to_string();
    Ok([stdout, stderr]
        .into_iter()
        .filter(|text| !text.is_empty())
        .collect::<Vec<_>>()
        .join("\n"))
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn parses_cli_and_user_agent_versions() {
        assert_eq!(
            parse_version("codex-cli 0.163.0"),
            Some(semver::Version::new(0, 163, 0))
        );
        assert_eq!(
            parse_version("codex_cli_rs/0.170.2 (Windows 10.0.26200; x86_64) vscode"),
            Some(semver::Version::new(0, 170, 2))
        );
        assert_eq!(is_too_old("codex-cli 0.120.0"), Some(true));
        assert_eq!(is_too_old("codex-cli 0.163.0"), Some(false));
        assert!(check_user_agent(Some("codex_cli_rs/0.99.0 (Linux)")).is_err());
        assert!(check_user_agent(Some("unknown")).is_ok());
    }

    #[test]
    fn detects_npm_shims_and_homebrew() {
        assert_eq!(
            detect_install_method(r"C:\nvm4w\nodejs\codex.cmd"),
            NativeCliInstallMethod::Npm
        );
        assert_eq!(
            detect_install_method("/opt/homebrew/Caskroom/codex/0.163.0/codex"),
            NativeCliInstallMethod::Homebrew
        );
    }
}
